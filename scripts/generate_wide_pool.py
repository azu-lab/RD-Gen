#!/usr/bin/env python3
"""Generate one core-count-independent DAG pool whose per-DAG utilization
(C/T) covers [--u-min, --u-max) with at least --target DAGs in every
--bin-width wide bin, for awkernel's offline test
(rd_gen_to_dags/examples/theory_vs_reality.rs).

Why not a single run_generator.py call: RD-Gen draws the utilization
uniformly, but a DAG whose critical path reaches its period is dropped
(Constrained deadlines, L >= T), and that gets far more frequent as C/T
grows (about 56% survive at C/T 2-3, 22% at 4-5, 6% at 5-6 with the
fanout16 shape). A uniform draw therefore leaves the high end thin. This
script generates the range in segments, measures how many DAGs survive per
bin, and draws more only where bins are short, until every bin has
--target DAGs (or a bin turns out to be practically unreachable).

Nothing here depends on the core count m or the set size N: the offline
test picks them later. The pool only has to reach far enough in C/T:
u_norm_max * m / N must stay below --u-max.

Every run uses the base config unchanged except for the seed, the number
of DAGs, the utilization range and the figure output, so the pool has the
same DAG shape, period and deadline mode as the base config. Seeds are
derived from --seed and the run index, so the same arguments give the same
pool. The merged pool lands in <dest>/DAGs/dag_<i>.yaml (numbered in
ascending C/T), with <dest>/pool_info.json recording every run and the
per-bin counts, and a copy of the base config.

Output formats: --yaml/--no-yaml, --pdf/--no-pdf, --png/--no-png,
--svg/--no-svg, --eps/--no-eps choose which files are written per DAG
(dag_<i>.<ext>, the same number for every format of one DAG). The default
is YAML and PDF. The offline test reads only the YAML, so --no-yaml makes a
pool for looking at, not for the offline test. Figures are drawn by
Graphviz (no random numbers), so they do not change which DAGs are
generated; they do make generation slower.

Usage (from the RD-Gen directory):
    venv/bin/python3 scripts/generate_wide_pool.py --dest test/awkernel_wide_pool
"""
import argparse
import copy
import hashlib
import json
import math
import shutil
import subprocess
import sys
import tempfile
import time
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

import yaml  # type: ignore

RD_GEN_DIR = Path(__file__).resolve().parent.parent
DEFAULT_BASE_CONFIG = RD_GEN_DIR / "sample_config" / "chain_based" / "theory_vs_reality_pool_fanout16.yaml"
# RD-Gen expands "(start, stop, step)" with numpy.arange: stop is excluded.
UTIL_STEP = 0.001
# A first guess of the survival rate, used only to size each segment's
# first run; later runs use the measured rate.
INITIAL_SURVIVAL_GUESS = 0.7
# Floor for a measured survival rate, so a bin with no survivor yet still
# gets a finite (large) request instead of a division by zero.
MIN_SURVIVAL_RATE = 0.002
# Extra draws on top of the estimate, so one more run is usually enough.
OVERDRAW = 1.15
# Largest single run. A bin that still needs more after its share of this
# is retried in later rounds (up to --max-rounds).
MAX_DAGS_PER_RUN = 60_000
# Files written per DAG: the DAG itself (YAML) and RD-Gen's figure formats.
FORMAT_DEFAULTS = {"yaml": True, "pdf": True, "png": False, "svg": False, "eps": False}
FIGURE_FORMATS = ("pdf", "png", "svg", "eps")


def parse_args():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--dest", type=Path, required=True,
                   help="output directory (must not exist unless --force); the pool goes to <dest>/DAGs")
    p.add_argument("--base-config", type=Path, default=DEFAULT_BASE_CONFIG,
                   help="RD-Gen config giving the DAG shape, period and deadline mode "
                        f"(default: {DEFAULT_BASE_CONFIG.relative_to(RD_GEN_DIR)})")
    p.add_argument("--u-min", type=float, default=0.01, help="lowest per-DAG C/T (default: 0.01)")
    p.add_argument("--u-max", type=float, default=5.0, help="per-DAG C/T upper bound, exclusive (default: 5.0)")
    p.add_argument("--bin-width", type=float, default=0.1, help="C/T bin width for --target (default: 0.1)")
    p.add_argument("--target", type=int, default=300, help="minimum DAGs per bin (default: 300)")
    p.add_argument("--segment-width", type=float, default=0.5,
                   help="C/T width generated by one run (default: 0.5)")
    p.add_argument("--seed", type=int, default=0, help="base seed; run k uses seed*100000+k (default: 0)")
    p.add_argument("--jobs", type=int, default=4, help="parallel run_generator.py processes (default: 4)")
    p.add_argument("--max-rounds", type=int, default=6,
                   help="give up on a bin still short after this many rounds (default: 6)")
    p.add_argument("--force", action="store_true", help="delete --dest first if it exists")
    for fmt, default in FORMAT_DEFAULTS.items():
        p.add_argument(f"--{fmt}", action=argparse.BooleanOptionalAction, default=default,
                       help=f"write dag_<i>.{fmt} for every DAG (default: {'on' if default else 'off'})")
    args = p.parse_args()
    if not (0 < args.u_min < args.u_max):
        p.error("need 0 < --u-min < --u-max")
    if args.bin_width <= 0 or args.segment_width < args.bin_width:
        p.error("need 0 < --bin-width <= --segment-width")
    if args.target < 1 or args.jobs < 1 or args.max_rounds < 1:
        p.error("--target, --jobs and --max-rounds must be positive")
    args.formats = [fmt for fmt in FORMAT_DEFAULTS if getattr(args, fmt)]
    if not args.formats:
        p.error("choose at least one output format")
    if not args.yaml:
        print("note: --no-yaml: the pool will have no YAML, which the offline test needs", file=sys.stderr)
    return args


def bin_edges(u_min, u_max, width):
    """[(lo, hi), ...] covering [u_min, u_max); bins are aligned to
    multiples of `width`, so the first one may be narrower."""
    edges = []
    lo = u_min
    k = math.floor(u_min / width + 1e-9) + 1
    while lo < u_max - 1e-12:
        hi = min(round(k * width, 6), u_max)
        edges.append((round(lo, 6), hi))
        lo = hi
        k += 1
    return edges


def bin_index(u, edges):
    for i, (lo, hi) in enumerate(edges):
        if lo - 1e-9 <= u < hi - 1e-9:
            return i
    return None


def dag_utilization(path):
    """C/T of one RD-Gen DAG YAML."""
    with open(path) as f:
        dag = yaml.safe_load(f)
    nodes = dag["nodes"]
    volume = sum(n["execution_time"] for n in nodes)
    period = next(n["period"] for n in nodes if "period" in n)
    return volume / period


def make_run_config(base, seed, count, lo, hi, formats):
    cfg = copy.deepcopy(base)
    cfg["Seed"] = seed
    cfg["Number of DAGs"] = count
    cfg["Properties"]["Multi-rate"]["Whole-DAG utilization"] = {"Random": f"({lo:.3f}, {hi:.3f}, {UTIL_STEP})"}
    outputs = cfg.setdefault("Output formats", {})
    # YAML is always generated: it is what this script measures C/T on.
    # Whether it is copied into the pool is decided at the merge.
    outputs.setdefault("DAG", {})["YAML"] = True
    figure = outputs.setdefault("Figure", {})
    for fmt in FIGURE_FORMATS:
        figure[fmt.upper()] = fmt in formats
    return cfg


def run_generator(base, seed, count, lo, hi, formats, work_dir):
    """One run_generator.py call; returns [(utilization, path)] of the DAGs
    it produced (the dropped ones never appear)."""
    run_dir = Path(work_dir) / f"run_{seed}"
    run_dir.mkdir()
    cfg_path = run_dir / "config.yaml"
    with open(cfg_path, "w") as f:
        yaml.safe_dump(make_run_config(base, seed, count, lo, hi, formats), f, sort_keys=False)
    out_dir = run_dir / "out"  # must not exist: run_generator.py asks before overwriting
    result = subprocess.run(
        [sys.executable, str(RD_GEN_DIR / "run_generator.py"), "-c", str(cfg_path), "-d", str(out_dir)],
        cwd=RD_GEN_DIR, stdin=subprocess.DEVNULL, capture_output=True, text=True,
    )
    if result.returncode != 0:
        raise RuntimeError(f"run_generator.py failed for seed {seed}:\n{result.stderr[-2000:]}")
    return [(dag_utilization(p), p) for p in sorted(out_dir.rglob("dag_*.yaml"))]


def main():
    args = parse_args()
    base_text = args.base_config.read_text()
    base = yaml.safe_load(base_text)
    if args.dest.exists():
        if not args.force:
            sys.exit(f"{args.dest} exists; pass --force to replace it")
        shutil.rmtree(args.dest)

    edges = bin_edges(args.u_min, args.u_max, args.bin_width)
    segments = []  # (first bin, last bin + 1)
    start = 0
    while start < len(edges):
        end = start
        while end < len(edges) and edges[end][1] - edges[start][0] <= args.segment_width + 1e-9:
            end += 1
        end = max(end, start + 1)
        segments.append((start, end))
        start = end

    kept = [[] for _ in edges]       # (utilization, seed, YAML path) per bin
    drawn = [0.0 for _ in edges]     # expected draws that landed in each bin
    runs = []
    next_run = 0
    t_start = time.time()

    with tempfile.TemporaryDirectory(prefix="wide_pool_") as work_dir:
        for round_no in range(1, args.max_rounds + 1):
            requests = []
            for first, last in segments:
                short = [b for b in range(first, last) if len(kept[b]) < args.target]
                if not short:
                    continue
                # Draw only over the short bins' span.
                lo_bin, hi_bin = short[0], short[-1] + 1
                lo, hi = edges[lo_bin][0], edges[hi_bin - 1][1]
                need = 0.0
                for b in short:
                    rate = (len(kept[b]) / drawn[b]) if drawn[b] > 0 else INITIAL_SURVIVAL_GUESS
                    rate = max(rate, MIN_SURVIVAL_RATE)
                    share = (edges[b][1] - edges[b][0]) / (hi - lo)
                    need = max(need, (args.target - len(kept[b])) / rate / share)
                count = min(MAX_DAGS_PER_RUN, max(50, math.ceil(need * OVERDRAW)))
                requests.append((args.seed * 100_000 + next_run, count, lo, hi, lo_bin, hi_bin))
                next_run += 1
            if not requests:
                break
            print(f"[round {round_no}] {len(requests)} runs, {sum(r[1] for r in requests)} DAGs requested",
                  flush=True)

            with ThreadPoolExecutor(max_workers=args.jobs) as pool:
                futures = [pool.submit(run_generator, base, seed, count, lo, hi, args.formats, work_dir)
                           for seed, count, lo, hi, _, _ in requests]
                results = [f.result() for f in futures]

            for (seed, count, lo, hi, lo_bin, hi_bin), dags in zip(requests, results):
                for b in range(lo_bin, hi_bin):
                    drawn[b] += count * (edges[b][1] - edges[b][0]) / (hi - lo)
                survivors = 0
                for u, path in dags:
                    b = bin_index(u, edges)
                    if b is None:
                        continue
                    kept[b].append((u, seed, path))
                    survivors += 1
                runs.append({"seed": seed, "u_range": [lo, hi], "requested": count, "survived": survivors})

            short = [b for b in range(len(edges)) if len(kept[b]) < args.target]
            print(f"[round {round_no}] {sum(len(k) for k in kept)} DAGs kept, {len(short)} bins short "
                  f"({time.time() - t_start:.0f}s)", flush=True)

        # Merge while the work dir still exists: every format of one DAG
        # gets the same new number.
        dags_dir = args.dest / "DAGs"
        dags_dir.mkdir(parents=True)
        merged = sorted((u, seed, str(path)) for bin_dags in kept for u, seed, path in bin_dags)
        missing = 0
        for i, (_, _, path) in enumerate(merged):
            for fmt in args.formats:
                src = Path(path).with_suffix(f".{fmt}")
                if src.exists():
                    shutil.copyfile(src, dags_dir / f"dag_{i}.{fmt}")
                else:
                    missing += 1
        if missing:
            print(f"WARNING: {missing} files RD-Gen did not write were skipped", file=sys.stderr)
    shutil.copyfile(args.base_config, args.dest / "base_config.yaml")

    per_bin = [{"u_range": [lo, hi], "count": len(kept[b])} for b, (lo, hi) in enumerate(edges)]
    short = [entry for entry in per_bin if entry["count"] < args.target]
    try:
        commit = subprocess.run(["git", "rev-parse", "HEAD"], cwd=RD_GEN_DIR, capture_output=True,
                                text=True, check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        commit = None
    info = {
        "command": " ".join([Path(sys.argv[0]).name] + sys.argv[1:]),
        "base_config": str(args.base_config),
        "base_config_sha256": hashlib.sha256(base_text.encode()).hexdigest(),
        "rd_gen_commit": commit,
        "u_min": args.u_min,
        "u_max": args.u_max,
        "bin_width": args.bin_width,
        "target_per_bin": args.target,
        "seed": args.seed,
        "formats": args.formats,
        "total_dags": len(merged),
        "runs": runs,
        "bins": per_bin,
        "short_bins": short,
    }
    (args.dest / "pool_info.json").write_text(json.dumps(info, indent=1) + "\n")

    print(f"wrote {len(merged)} DAGs to {dags_dir} ({time.time() - t_start:.0f}s)")
    if short:
        print(f"WARNING: {len(short)} bins below --target {args.target}:", file=sys.stderr)
        for entry in short:
            lo, hi = entry["u_range"]
            print(f"  [{lo:.2f}, {hi:.2f}): {entry['count']}", file=sys.stderr)


if __name__ == "__main__":
    main()
